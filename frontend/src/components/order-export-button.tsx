
"use client";

import { useRef, useState } from "react";
import { useRouter } from "next/navigation";

import type { OrderStatus } from "@/lib/order-desk-orders";

type Props = {
  orderId: number;
  status: OrderStatus;
};

export default function OrderExportButton({
  orderId,
  status,
}: Props) {
  const router = useRouter();

  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [notice, setNotice] = useState("");

  const downloading = useRef(false);

  async function handleExport() {
    if (downloading.current) return;

    downloading.current = true;
    setBusy(true);
    setError("");
    setNotice("");

    try {
      const response = await fetch(
        `/api/order-desk/orders/${orderId}/export`,
        {
          method: "POST",
          credentials: "same-origin",
        }
      );

      if (response.status === 401) {
        window.location.replace("/login");
        return;
      }

      if (!response.ok) {
        const data: unknown = await response
          .json()
          .catch(() => null);

        let message = `Export failed (${response.status}).`;

        if (
          data &&
          typeof data === "object" &&
          "detail" in data &&
          typeof data.detail === "string"
        ) {
          message = data.detail;
        }

        throw new Error(message);
      }

      const blob = await response.blob();

      const url = URL.createObjectURL(blob);
      const anchor = document.createElement("a");

      anchor.href = url;
      anchor.download = `dukaanflow-order-${orderId}.xml`;

      document.body.appendChild(anchor);
      anchor.click();
      anchor.remove();

      // Allow the browser time to start the download.
      window.setTimeout(
        () => URL.revokeObjectURL(url),
        30000
      );

      setNotice(
        "XML prepared for download. Import and verify it in TallyPrime separately."
      );

      router.refresh();
    } catch (err) {
      setError(
        err instanceof Error
          ? err.message
          : "Unable to export this order."
      );

      router.refresh();
    } finally {
      downloading.current = false;
      setBusy(false);
    }
  }

  if (status === "on_hold") {
    return (
      <div className="mt-6 rounded-xl bg-amber-50 p-4 text-sm text-amber-800">
        Resume this order before exporting it.
      </div>
    );
  }

  return (
    <section className="mt-6 border-t border-[#edf0ec] pt-6">
      <h3 className="text-base font-semibold">
        Tally export
      </h3>

      <p className="mt-2 text-xs leading-5 text-[#64766a]">
        Generate a Sales Order XML file for import
        into a configured TallyPrime company.
      </p>

      {error && (
        <p
          role="alert"
          className="mt-4 rounded-lg bg-red-50 p-3 text-sm text-red-700"
        >
          {error}
        </p>
      )}

      {notice && (
        <p
          role="status"
          className="mt-4 rounded-lg bg-[#edf5ef] p-3 text-sm text-[#176b52]"
        >
          {notice}
        </p>
      )}

      <button
        type="button"
        disabled={busy}
        onClick={() => void handleExport()}
        className="mt-4 min-h-12 w-full rounded-xl bg-[#176b52] px-5 text-sm font-semibold text-white disabled:opacity-50"
      >
        {busy
          ? "Preparing XML..."
          : status === "exported"
            ? "Download XML again"
            : "Export Tally XML"}
      </button>

      <p className="mt-3 text-xs leading-5 text-[#64766a]">
        Exported means the file was generated by
        DukaanFlow. It does not confirm successful
        import into TallyPrime.
      </p>
    </section>
  );
}
